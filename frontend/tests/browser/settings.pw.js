import { test, expect } from '@playwright/test'
import { fixtures, installMockApi, roles } from './mockApi.js'

const form = (page) => page.getByRole('form', { name: 'Change password', exact: true })
const writes = (state) => state.calls.filter((call) => call.path === '/auth/change-password')
async function open(context, page, role = 'student') {
  const state = fixtures(role)
  await installMockApi(context, state)
  await page.goto('/settings')
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  return state
}
async function fill(page, { current = 'CurrentPassword123', password = 'UpdatedPassword123', confirm = password } = {}) {
  await form(page).getByLabel('Current password', { exact: true }).fill(current)
  await form(page).getByLabel('New password', { exact: true }).fill(password)
  await form(page).getByLabel('Confirm new password', { exact: true }).fill(confirm)
}

for (const role of roles) test(`${role}: Settings replaces the footer and opens permitted account preferences`, async ({ context, page }) => {
  const state = await open(context, page, role)
  const sidebar = page.getByRole('complementary', { name: 'Desktop sidebar', exact: true })
  const footer = sidebar.getByRole('navigation', { name: 'Account navigation', exact: true })
  await expect(footer.getByRole('link', { name: 'Settings', exact: true })).toHaveAttribute('aria-current', 'location')
  await expect(sidebar).not.toContainText('University portal')
  await expect(page.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
  await expect(form(page).locator('input[type="password"]')).toHaveCount(3)
  await expect(page.getByRole('link', { name: 'My academic profile', exact: true })).toHaveCount(role === 'student' ? 1 : 0)
  await page.getByRole('link', { name: 'Edit my account', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await footer.getByRole('link', { name: 'Settings', exact: true }).click()
  await expect(page).toHaveURL(/\/settings$/)
  expect(state.unexpected).toEqual([])
  expect(state.calls.every((call) => call.method === 'GET')).toBe(true)
})

test('Settings appearance persists and stays synchronized with the navbar theme toggle', async ({ context, page }) => {
  const state = await open(context, page)
  await page.getByRole('radio', { name: 'Dark', exact: true }).check()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('button', { name: 'Dark mode', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await page.evaluate(() => localStorage.getItem('sims-theme'))).toBe('dark')
  await page.reload()
  await expect(page.getByRole('radio', { name: 'Dark', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click()
  await expect(page.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(writes(state)).toHaveLength(0)
})

test('password validation focuses invalid fields and incorrect-current errors can be corrected without losing the new password', async ({ context, page }) => {
  const state = await open(context, page)
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(form(page).getByLabel('Current password', { exact: true })).toBeFocused()
  expect(writes(state)).toHaveLength(0)
  await fill(page, { password: 'CurrentPassword123' })
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(form(page).getByLabel('New password', { exact: true })).toBeFocused()
  expect(writes(state)).toHaveLength(0)
  await fill(page, { confirm: 'DifferentPassword123' })
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(form(page).getByLabel('Confirm new password', { exact: true })).toBeFocused()
  expect(writes(state)).toHaveLength(0)
  await fill(page, { current: 'WrongPassword123' })
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(form(page).getByText('Current password is incorrect.', { exact: true })).toBeVisible()
  await expect(form(page).getByLabel('Current password', { exact: true })).toBeFocused()
  await expect(form(page).getByLabel('New password', { exact: true })).toHaveValue('UpdatedPassword123')
  await form(page).getByLabel('Current password', { exact: true }).fill('CurrentPassword123')
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(form(page).getByRole('status')).toHaveText('Password changed successfully.')
  expect(writes(state)).toHaveLength(2)
  expect(state.unexpected).toEqual([])
})

test('a password change is explicit, locked while saving, clears secrets and works for the next sign-in', async ({ context, page }) => {
  const state = await open(context, page)
  await fill(page)
  await form(page).getByRole('button', { name: 'Show passwords', exact: true }).click()
  await expect(form(page).getByLabel('New password', { exact: true })).toHaveAttribute('type', 'text')
  expect(writes(state)).toHaveLength(0)
  let release
  state.holdWrites = new Promise((resolve) => { release = resolve })
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect.poll(() => writes(state).length).toBe(1)
  await expect(form(page).getByLabel('Current password', { exact: true })).toBeDisabled()
  await expect(form(page).getByRole('button', { name: 'Hide passwords', exact: true })).toBeDisabled()
  await form(page).evaluate((element) => { element.requestSubmit(); element.requestSubmit() })
  expect(writes(state)).toHaveLength(1)
  release(); state.holdWrites = null
  await expect(form(page).getByRole('status')).toHaveText('Password changed successfully.')
  for (const label of ['Current password', 'New password', 'Confirm new password']) await expect(form(page).getByLabel(label, { exact: true })).toHaveValue('')
  await expect(form(page).locator('input[type="password"]')).toHaveCount(3)
  expect(writes(state)[0].values).toEqual({ currentPassword: 'CurrentPassword123', newPassword: 'UpdatedPassword123' })
  expect(await page.evaluate(() => [...Object.values(localStorage), ...Object.values(sessionStorage)].some((value) => /CurrentPassword123|UpdatedPassword123/.test(value)))).toBe(false)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByLabel('Email address', { exact: true }).fill('student@example.test')
  await page.getByLabel('Password', { exact: true }).fill('CurrentPassword123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid credentials.')
  await page.getByLabel('Password', { exact: true }).fill('UpdatedPassword123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  expect(state.unexpected).toEqual([])
})

test('show/clear commands do not write a password and leaving Settings discards unsaved secrets', async ({ context, page }) => {
  const state = await open(context, page)
  await fill(page)
  await form(page).getByRole('button', { name: 'Show passwords', exact: true }).click()
  await expect(form(page).locator('input[type="text"]')).toHaveCount(3)
  await form(page).getByRole('button', { name: 'Clear passwords', exact: true }).click()
  await expect(form(page).getByLabel('Current password', { exact: true })).toHaveValue('')
  await expect(form(page).locator('input[type="password"]')).toHaveCount(3)
  await fill(page)
  await page.getByRole('link', { name: 'Edit my account', exact: true }).click()
  await page.getByRole('navigation', { name: 'Account navigation', exact: true }).getByRole('link', { name: 'Settings', exact: true }).first().click()
  await expect(form(page).getByLabel('New password', { exact: true })).toHaveValue('')
  expect(writes(state)).toHaveLength(0)
})

test('uncertain password writes never claim success or automatically resubmit', async ({ context, page }) => {
  const state = await open(context, page)
  state.failures.push({ path: '/auth/change-password', method: 'PATCH', status: 500 })
  await fill(page)
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(form(page).getByRole('alert')).toContainText('Password change could not be confirmed.')
  await expect(form(page).getByRole('status')).toHaveCount(0)
  await expect(form(page).getByLabel('Current password', { exact: true })).toBeDisabled()
  await expect(form(page).getByLabel('Current password', { exact: true })).toHaveValue('')
  await form(page).evaluate((element) => element.requestSubmit())
  expect(writes(state)).toHaveLength(1)
  await form(page).getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
})

test('expired password requests sign out and unsigned visitors cannot open Settings', async ({ context, page }) => {
  const state = await open(context, page)
  state.failures.push({ path: '/auth/change-password', method: 'PATCH', status: 401 })
  await fill(page)
  await form(page).getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/settings')
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByLabel('Current password', { exact: true })).toHaveCount(0)
})

test('mobile footer Settings opens the page and closes the navigation drawer', async ({ context, page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await open(context, page, 'admin')
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Navigation', exact: true })
  const settings = drawer.getByRole('link', { name: 'Settings', exact: true })
  await expect(settings).toBeVisible()
  const box = await settings.boundingBox()
  expect(box.y + box.height).toBeLessThanOrEqual(568)
  await settings.click()
  await expect(page).toHaveURL(/\/settings$/)
  await expect(drawer).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
})

